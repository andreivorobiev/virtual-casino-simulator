// Import filesystem reads and writes for the one bounded generated Swift package file.
import { readFile, writeFile } from "node:fs/promises";
// Import path resolution so direct execution cannot select an alternate generated target.
import path from "node:path";
// Import URL conversion for a host-independent script entrypoint comparison.
import { fileURLToPath } from "node:url";

// Enumerate the exact generated local Capacitor products governed by the current lockfile.
const EXPECTED_LOCAL_PACKAGES = new Map([
  // Bind the App lifecycle plugin to its exact Swift product and package folder.
  ["CapacitorApp", { packageFolder: "app", virtualStoreEntry: "@capacitor+app@8.1.0_@capacitor+core@8.4.2" }],
  // Bind the system-browser plugin to its exact Swift product and package folder.
  ["CapacitorBrowser", { packageFolder: "browser", virtualStoreEntry: "@capacitor+browser@8.0.3_@capacitor+core@8.4.2" }],
  // Bind the keyboard lifecycle plugin to its exact Swift product and package folder.
  ["CapacitorKeyboard", { packageFolder: "keyboard", virtualStoreEntry: "@capacitor+keyboard@8.0.5_@capacitor+core@8.4.2" }],
  // Bind the network lifecycle plugin to its exact Swift product and package folder.
  ["CapacitorNetwork", { packageFolder: "network", virtualStoreEntry: "@capacitor+network@8.0.1_@capacitor+core@8.4.2" }],
]);
// Match only Capacitor CLI local-package declarations without rewriting unrelated Swift text.
const LOCAL_PACKAGE_PATTERN = /(\.package\(name: "([^"]+)", path: ")([^"\r\n]+)("\),?)/g;

// Normalize Capacitor's host-specific generated local paths into one committed POSIX representation. (TEST-172)
export function normalizeCapacitorPackageText(source) {
  // Reject non-text inputs before applying any generated-source transformation.
  if (typeof source !== "string") throw new Error("Generated Package.swift must be text.");
  // Track every exact product so missing, duplicate, or unexpected plugin entries fail closed.
  const seen = new Set();
  // Rewrite only validated local path values while preserving all surrounding generated Swift bytes.
  const normalized = source.replace(LOCAL_PACKAGE_PATTERN, (entry, prefix, product, rawPath, suffix) => {
    // Reject products outside the exact current Capacitor plugin inventory.
    if (!EXPECTED_LOCAL_PACKAGES.has(product) || seen.has(product)) throw new Error("Unexpected generated Capacitor package entry.");
    // Convert only platform separators; no path segments are added, removed, or resolved implicitly.
    const portablePath = rawPath.replaceAll("\\", "/");
    // Read the exact package folder and lockfile-derived virtual-store directory for this product.
    const expected = EXPECTED_LOCAL_PACKAGES.get(product);
    // Construct the sole current path accepted after separator normalization.
    const expectedPath = `../../../node_modules/.pnpm/${expected.virtualStoreEntry}/node_modules/@capacitor/${expected.packageFolder}`;
    // Stop if Capacitor emits a dot segment, escape, foreign dependency, or changed lockfile directory.
    if (portablePath !== expectedPath) throw new Error("Generated Capacitor package path did not match the exact governed virtual-store entry.");
    // Record the validated product before returning its canonical declaration.
    seen.add(product);
    // Preserve the generated declaration while replacing only its path separators.
    return `${prefix}${portablePath}${suffix}`;
  });
  // Require every exact current plugin once so an incomplete sync can never look deterministic.
  if (seen.size !== EXPECTED_LOCAL_PACKAGES.size) throw new Error("Generated Package.swift is missing governed Capacitor package entries.");
  // Return the host-independent generated text for comparison or persistence.
  return normalized;
}

// Normalize only the exact generated Swift package owned by Capacitor sync.
export async function normalizeGeneratedCapacitorPackage() {
  // Resolve the mobile workspace from this script rather than caller-controlled working directory state.
  const mobileRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  // Bind the sole mutable target below the checked-in iOS generated project.
  const packagePath = path.join(mobileRoot, "ios", "App", "CapApp-SPM", "Package.swift");
  // Read the generated bytes after cap sync completes successfully.
  const source = await readFile(packagePath, "utf8");
  // Produce the exact canonical cross-host representation with all safety checks applied.
  const normalized = normalizeCapacitorPackageText(source);
  // Avoid a needless filesystem write when Linux already generated the canonical bytes.
  if (normalized === source) return false;
  // Persist only the canonical path-separator repair while retaining existing line endings and content.
  await writeFile(packagePath, normalized, "utf8");
  // Report that the bounded generated file changed for deterministic command diagnostics.
  return true;
}

// Detect direct script execution without running filesystem mutation during unit-test imports.
const invokedDirectly = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
// Normalize the one generated file only when invoked by the reviewed sync command.
if (invokedDirectly) await normalizeGeneratedCapacitorPackage();
